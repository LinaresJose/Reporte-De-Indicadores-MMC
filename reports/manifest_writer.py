"""manifest_writer.py — LYNX Report System.

Generates CSV manifest files that list all produced report files
(vendor PDFs and regional Excel files), enabling easy auditing and
downstream integration with other systems.

Manifests are written as UTF-8 BOM CSV files for compatibility with
Microsoft Excel's default CSV import behavior in Windows locales.

Typical usage::

    from reports.manifest_writer import write_vendor_manifest, write_regional_manifest

    vendor_manifest_path = write_vendor_manifest(records, output_dir)
    regional_manifest_path = write_regional_manifest(saved_paths, output_dir)
"""

from __future__ import annotations

import csv
import logging
import re
import unicodedata
from datetime import datetime
from pathlib import Path
from typing import Dict, List, Sequence

from core.models import VendorRecord

logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

VENDOR_MANIFEST_FILENAME = "manifest_indicadores_vendedores.csv"
REGIONAL_MANIFEST_FILENAME = "manifest_indicadores_regionales.csv"

# CSV headers
VENDOR_CSV_HEADERS = [
    "NombreArchivo",
    "VendedorNombre",
    "Zona",
    "Region",
    "FechaGeneracion",
    "TipoReporte",
]

REGIONAL_CSV_HEADERS = [
    "NombreArchivo",
    "Region",
    "FechaGeneracion",
    "TipoReporte",
]


# ---------------------------------------------------------------------------
# Private helpers
# ---------------------------------------------------------------------------


def _normalize_filename(text: str) -> str:
    """Convert *text* into a filesystem-safe ASCII string.

    Strips accents, removes characters that are invalid in Windows file names,
    collapses whitespace to underscores, and converts to title-cased words.

    Args:
        text: Arbitrary string (may contain accents, spaces, symbols).

    Returns:
        A clean ASCII string suitable for use in a file name.

    Examples::

        >>> _normalize_filename("María José (Ventas)")
        'Maria_Jose_Ventas'
        >>> _normalize_filename("ANDES & LLANOS")
        'ANDES_LLANOS'
    """
    # Decompose unicode → remove combining diacritical marks (accents)
    nfd = unicodedata.normalize("NFD", text)
    ascii_text = nfd.encode("ascii", "ignore").decode("ascii")

    # Remove characters not allowed in Windows file names
    safe = re.sub(r'[\\/:*?"<>|]', "", ascii_text)

    # Replace whitespace sequences and hyphens with single underscore
    safe = re.sub(r"[\s\-]+", "_", safe.strip())

    # Remove any remaining non-word characters (keep letters, digits, _)
    safe = re.sub(r"[^\w]", "", safe)

    return safe or "SIN_NOMBRE"


def _now_iso() -> str:
    """Return the current local datetime as an ISO-8601 string (no microseconds).

    Returns:
        String like ``"2026-11-06T16:30:00"``.
    """
    return datetime.now().strftime("%Y-%m-%dT%H:%M:%S")


def _write_csv(path: Path, headers: List[str], rows: List[List[str]]) -> None:
    """Write *rows* to a UTF-8-BOM CSV file at *path*.

    UTF-8-BOM ensures Microsoft Excel opens the file with correct encoding
    without an explicit import wizard on Spanish-locale Windows machines.

    Args:
        path: Destination file path (parent directory must exist).
        headers: Column header strings.
        rows: List of rows; each row must have the same length as *headers*.

    Raises:
        OSError: If the file cannot be written (permissions, disk full, etc.).
    """
    with path.open("w", newline="", encoding="utf-8-sig") as fh:
        writer = csv.writer(fh, delimiter=";")
        writer.writerow(headers)
        writer.writerows(rows)

    logger.debug("CSV written: %s (%d data rows)", path, len(rows))


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------


def write_vendor_manifest(
    records: Sequence[VendorRecord],
    output_dir: Path,
    pdf_subdir: str = "PDF_INDICADORES",
) -> Path:
    """Generate the vendor-level CSV manifest.

    For each vendor in *records* that has a PDF report, one row is added to
    the manifest describing the expected PDF file name, the vendor's identity,
    and when the manifest was generated.

    Only vendors whose budget data is populated are included (they are the ones
    for which a PDF is generated by :func:`reports.pdf_writer.generate_pdf_reports`).

    Args:
        records: Sequence of fully-computed :class:`~core.models.VendorRecord`
            objects, as returned by :func:`core.engine.calculate_general`.
        output_dir: Root output directory where manifests are stored (also the
            parent of *pdf_subdir*).
        pdf_subdir: Name of the sub-directory where PDF files are saved.
            Defaults to ``"PDF_INDICADORES"``.

    Returns:
        Absolute :class:`~pathlib.Path` of the written manifest CSV file.

    Raises:
        OSError: If the output directory cannot be written to.

    Example::

        path = write_vendor_manifest(records, Path("output"))
        print(f"Manifest at {path}")
    """
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    timestamp = _now_iso()
    rows: List[List[str]] = []

    for rec in records:
        # Only include vendors that have an associated PDF (i.e., have budget)
        if rec.presup_ventas == 0 and rec.presup_activacion == 0 and rec.presup_skus == 0:
            logger.debug(
                "Skipping vendor '%s' from manifest — no budget assigned.", rec.nombre
            )
            continue

        safe_name = _normalize_filename(rec.nombre)
        pdf_filename = f"Indicadores_{safe_name}.pdf"
        relative_path = str(Path(pdf_subdir) / pdf_filename)

        rows.append(
            [
                relative_path,
                rec.nombre,
                rec.zona,
                rec.region,
                timestamp,
                "PDF_INDIVIDUAL",
            ]
        )

    manifest_path = output_dir / VENDOR_MANIFEST_FILENAME
    _write_csv(manifest_path, VENDOR_CSV_HEADERS, rows)

    logger.info(
        "Vendor manifest written: %s (%d vendors)", manifest_path.name, len(rows)
    )
    return manifest_path


def write_regional_manifest(
    saved_paths: Dict[str, Path],
    output_dir: Path,
) -> Path:
    """Generate the regional-level CSV manifest.

    One row per region lists the Excel file that was produced for that region.

    Args:
        saved_paths: Mapping of ``{region_name: absolute_path_to_xlsx}``, as
            returned by :func:`reports.excel_writer.generate_excel_report`.
        output_dir: Root output directory where the manifest is stored.

    Returns:
        Absolute :class:`~pathlib.Path` of the written manifest CSV file.

    Raises:
        OSError: If the output directory cannot be written to.

    Example::

        regional_paths = {"CAPITAL": Path("output/CAPITAL_Indicadores.xlsx")}
        path = write_regional_manifest(regional_paths, Path("output"))
    """
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    timestamp = _now_iso()
    rows: List[List[str]] = []

    for region, file_path in sorted(saved_paths.items()):
        rows.append(
            [
                file_path.name,
                region,
                timestamp,
                "EXCEL_REGIONAL",
            ]
        )

    manifest_path = output_dir / REGIONAL_MANIFEST_FILENAME
    _write_csv(manifest_path, REGIONAL_CSV_HEADERS, rows)

    logger.info(
        "Regional manifest written: %s (%d regions)", manifest_path.name, len(rows)
    )
    return manifest_path
